// packages/shared/src/__tests__/thunder-keys.test.ts
//
// Thunder key derivation vectors.
//
// The v0.18 golden vector is the community vector for the eCash wallet's
// Thunder port (mnemonic "abandon abandon … about", empty passphrase, slot
// 9, address index 0): the address the 0.18 betanet node family derives.
// There is no equivalent public v0.19 vector yet — v0.19 correctness is
// pinned by internal-consistency tests (public/private derivation parity,
// determinism, round trips) and the byte rules read from thunder-rust
// v0.19.3 lib/wallet/bip32.rs; a true golden vector must be generated by
// running thunder-rust 0.19.3's own wallet (TODO, tracked).

import { describe, expect, it } from "vitest";
import { mnemonicToSeedSync } from "@scure/bip39";

import {
  deriveAccountKey,
  deriveAddressKey,
  deriveAddressPublicKey,
  derivationPath,
  schemeForNetwork,
  thunderMasterKey,
  toPublicKey,
  type ThunderPrivateKey,
} from "../sidechains/thunder/keys";
import { thunderAddress } from "../sidechains/thunder/address";
import { baseMul } from "../sidechains/thunder/crypto";

const ABANDON_X11_ABOUT =
  "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";

function accountFor(scheme: "thunder-v18" | "thunder-v19", mnemonic = ABANDON_X11_ABOUT): ThunderPrivateKey {
  const seed = mnemonicToSeedSync(mnemonic, "");
  return deriveAccountKey(seed, scheme);
}

describe("thunder key schemes", () => {
  it("maps networks to schemes: betanet v18, signet + mainnet v19", () => {
    expect(schemeForNetwork("betanet")).toBe("thunder-v18");
    expect(schemeForNetwork("signet")).toBe("thunder-v19");
    expect(schemeForNetwork("mainnet")).toBe("thunder-v19");
  });

  it("derivation path is m/43'/1899'/0'/9'/0'/i", () => {
    expect(derivationPath(0)).toBe("m/43'/1899'/0'/9'/0'/0");
    expect(derivationPath(17)).toBe("m/43'/1899'/0'/9'/0'/17");
  });

  it("GOLDEN v0.18: abandon×11 about, slot 9, index 0 → NKqSr4bQejFbKpd5yLQgWEiMJFx", () => {
    const account = accountFor("thunder-v18");
    const addressKey = deriveAddressKey(account, 0, "thunder-v18");
    const address = thunderAddress(baseMul(addressKey.scalar));
    expect(address).toBe("NKqSr4bQejFbKpd5yLQgWEiMJFx");
  });

  it("v0.18: neighboring indices derive distinct addresses", () => {
    const account = accountFor("thunder-v18");
    const a0 = thunderAddress(baseMul(deriveAddressKey(account, 0, "thunder-v18").scalar));
    const a1 = thunderAddress(baseMul(deriveAddressKey(account, 1, "thunder-v18").scalar));
    const a2 = thunderAddress(baseMul(deriveAddressKey(account, 2, "thunder-v18").scalar));
    expect(a0).not.toBe(a1);
    expect(a1).not.toBe(a2);
    // All Thunder addresses: base58 of 20 bytes → 26-28 chars.
    for (const a of [a0, a1, a2]) {
      expect(a).toMatch(/^[1-9A-HJ-NP-Za-km-z]{26,28}$/);
    }
  });

  it("v0.19: determinism — same seed, same keys", () => {
    const a1 = accountFor("thunder-v19");
    const a2 = accountFor("thunder-v19");
    expect(a1.scalar).toBe(a2.scalar);
    expect(a1.chainCode).toEqual(a2.chainCode);
  });

  it("v0.18 vs v0.19: same seed, DIFFERENT keys (hasher families diverged)", () => {
    const v18 = accountFor("thunder-v18");
    const v19 = accountFor("thunder-v19");
    expect(v18.scalar).not.toBe(v19.scalar);
    expect(v18.chainCode).not.toEqual(v19.chainCode);
  });

  it("watch-only: public derivation equals private derivation (both schemes)", () => {
    for (const scheme of ["thunder-v18", "thunder-v19"] as const) {
      const account = accountFor(scheme);
      const accountPub = toPublicKey(account);
      for (const index of [0, 1, 5, 19]) {
        const viaPrivate = baseMul(deriveAddressKey(account, index, scheme).scalar);
        const viaPublic = deriveAddressPublicKey(accountPub, index, scheme);
        expect(viaPublic).toEqual(viaPrivate);
      }
    }
  });

  it("public derivation refuses hardened indices", () => {
    const accountPub = toPublicKey(accountFor("thunder-v18"));
    expect(() => deriveAddressPublicKey(accountPub, 0x8000_0000, "thunder-v18")).toThrow();
  });

  it("master keys differ per scheme and are seed-bound", () => {
    const seed = mnemonicToSeedSync(ABANDON_X11_ABOUT, "");
    const other = mnemonicToSeedSync(
      "letter advice cage absurd amount doctor acoustic avoid letter advice cage above",
      "",
    );
    for (const scheme of ["thunder-v18", "thunder-v19"] as const) {
      const m1 = thunderMasterKey(seed, scheme);
      const m2 = thunderMasterKey(other, scheme);
      expect(m1.scalar).not.toBe(m2.scalar);
      expect(m1.chainCode).not.toEqual(m2.chainCode);
    }
  });

  it("hardened levels chain: account key depends on every level", () => {
    // m/43' alone differs from m/43'/1899'… — sanity that levels actually apply.
    const seed = mnemonicToSeedSync(ABANDON_X11_ABOUT, "");
    const master = thunderMasterKey(seed, "thunder-v18");
    const account = accountFor("thunder-v18");
    expect(master.scalar).not.toBe(account.scalar);
    expect(master.chainCode).not.toEqual(account.chainCode);
  });
});
